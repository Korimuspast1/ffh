fun stringsFor(language: String): Strings = when (language.lowercase()) {
    "ru" -> RU
    "en" -> EN
    else -> if (Locale.getDefault().language.lowercase() == "ru") RU else EN
}

val LocalStrings = staticCompositionLocalOf { EN }

@Composable
fun ProvideStrings(language: String, content: @Composable () -> Unit) {
    CompositionLocalProvider(LocalStrings provides stringsFor(language), content = content)
}
